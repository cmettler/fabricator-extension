"""Generates the distributed TPC-H / TPC-DS service suites.

Each benchmark's tables are split between local DuckDB and SQL Server in several fixed placements; every query must
return what the all-local run returns. The expected results are computed here, locally, from the same generator
(dbgen / dsdgen are deterministic for a scale factor), and the suites compare with `rowsort` (DuckDB's runner
compares numeric values approximately, so a double that differs in its last bits still matches).

usage: python -I scripts/gen_tpc_suites.py            (needs the duckdb python package of the build's version)
"""
import os
import random

import duckdb

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SF = "0.01"

BENCHES = {
    "tpch": {
        "facts": {"lineitem", "orders", "partsupp"},
        "pragma": "tpch",
        "gen": "dbgen",
        "queries": "tpch_queries",
    },
    "tpcds": {
        "facts": {"store_sales", "store_returns", "catalog_sales", "catalog_returns", "web_sales", "web_returns",
                  "inventory"},
        "pragma": "tpcds",
        "gen": "dsdgen",
        "queries": "tpcds_queries",
    },
}


def cell(v):
    """A value the way the sqllogictest runner prints it."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    s = str(v)
    return "(empty)" if s == "" else s


def placements(names, facts):
    rnd = random.Random("fabricator-tpc")
    return {
        "remote": set(names),
        "facts": {t for t in names if t in facts},
        "dims": {t for t in names if t not in facts},
        "mixed": {t for t in names if rnd.random() < 0.5},
    }


def generate(bench):
    cfg = BENCHES[bench]
    con = duckdb.connect()
    con.execute(f"INSTALL {bench}; LOAD {bench}")
    con.execute(f"CREATE SCHEMA {bench}")
    con.execute(f"CALL {cfg['gen']}(sf = {SF}, schema = '{bench}')")
    names = [r[0] for r in con.execute(
        f"SELECT table_name FROM duckdb_tables() WHERE schema_name = '{bench}' ORDER BY 1").fetchall()]
    places = placements(names, cfg["facts"])
    rschema = f"{bench}_t"
    nrs = [r[0] for r in con.execute(f"SELECT query_nr FROM {cfg['queries']}() ORDER BY 1").fetchall()]

    out = []
    w = out.append
    w(f"# name: test/verify_{bench}_mssql.test")
    w(f"# description: {bench.upper()} at SF {SF} with its tables split between local DuckDB and SQL Server in")
    w("#              several placements (all remote, the facts remote, the dimensions remote, a fixed random split);")
    w("#              every query must return what the all-local run returns. GENERATED by scripts/gen_tpc_suites.py")
    w("#              — edit that, not this file. The expected results are the local answers (rowsort; numeric")
    w("#              values compare approximately).")
    w("# group: [fabricator]")
    w("")
    w("require fabricator")
    w("")
    w(f"require {bench}")
    w("")
    w("require-env MSSQL_TESTDB_DSN")
    w("")
    w("statement ok")
    w("ATTACH '${MSSQL_TESTDB_DSN}' AS rp (TYPE fabricator, remote_pushdown 'true');")
    w("")
    w("statement ok")
    w(f"CREATE SCHEMA memory.{bench}")
    w("")
    w("statement ok")
    w(f"CALL {cfg['gen']}(sf = {SF}, catalog = 'memory', schema = '{bench}');")
    w("")
    w("statement ok")
    w(f"SELECT fabricator_exec('rp', 'IF SCHEMA_ID(''{rschema}'') IS NULL EXEC(''CREATE SCHEMA {rschema}'')', "
      "refresh_cache := true);")
    w("")
    for t in names:
        w("statement ok")
        w(f"CREATE OR REPLACE TABLE rp.{rschema}.{t} AS SELECT * FROM memory.{bench}.{t};")
        w("")
    for p, remote in places.items():
        w("statement ok")
        w(f"CREATE SCHEMA memory.mix_{p}")
        w("")
        for t in names:
            src = f"rp.{rschema}.{t}" if t in remote else f"memory.{bench}.{t}"
            w("statement ok")
            w(f"CREATE VIEW memory.mix_{p}.{t} AS SELECT * FROM {src}")
            w("")
    w("# placements: " + "; ".join(f"{p} = {', '.join(sorted(r)) or '(none)'}" for p, r in places.items()))
    w(f"foreach placement {' '.join(places)}")
    w("")
    w("statement ok")
    w("USE memory.mix_${placement}")
    w("")
    con.execute(f"USE memory.{bench}")
    for nr in nrs:
        rows = con.execute(f"PRAGMA {cfg['pragma']}({nr})").fetchall()
        ncols = len(con.description)
        text_rows = sorted(tuple(cell(v) for v in r) for r in rows)
        w(f"query {'T' * ncols} rowsort")
        w(f"PRAGMA {cfg['pragma']}({nr})")
        w("----")
        for r in text_rows:
            w("\t".join(r))
        w("")
    w("endloop")
    w("")
    w("statement ok")
    w("USE memory.main")
    w("")
    for t in names:
        w("statement ok")
        w(f"DROP TABLE rp.{rschema}.{t}")
        w("")
    path = os.path.join(REPO, "test", f"verify_{bench}_mssql.test")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{path}: {len(nrs)} queries x {len(places)} placements, {sum(1 for l in out if l.startswith('query'))} "
          f"query blocks")


if __name__ == "__main__":
    for b in BENCHES:
        generate(b)
